<?php
declare(strict_types=1);

namespace App\Core;

/** Writes config/config.php (with freshly generated secrets), creates the database objects and verifies the environment. */
final class Installer
{
    /** @return array<string,array{ok:bool,detail:string}> */
    public static function requirements(): array
    {
        $r = [];
        $r['PHP 8.1 or newer'] = ['ok' => PHP_VERSION_ID >= 80100, 'detail' => PHP_VERSION];
        foreach (['pdo_mysql', 'mbstring', 'openssl', 'curl', 'json', 'ctype'] as $ext) $r["PHP extension $ext"] = ['ok' => extension_loaded($ext), 'detail' => extension_loaded($ext) ? 'loaded' : 'missing'];
        $r['Argon2id password hashing'] = ['ok' => true, 'detail' => defined('PASSWORD_ARGON2ID') ? 'available' : 'not available: bcrypt will be used (fine)'];
        foreach (['config', 'storage', 'storage/logs', 'storage/uploads', 'storage/cache', 'storage/mail'] as $d) {
            $p = APP_ROOT . '/' . $d;
            if (!is_dir($p)) @mkdir($p, 0750, true);
            $r["Writable folder $d"] = ['ok' => is_dir($p) && is_writable($p), 'detail' => is_dir($p) ? (is_writable($p) ? 'writable' : 'not writable') : 'missing'];
        }
        return $r;
    }

    /**
     * @param array{db:array{host:string,port:int|string,name:string,user:string,pass:string,socket?:string},app_url:string,env?:string,mail?:array} $in
     */
    public static function writeConfig(array $in): string
    {
        $cfg = [
            'env' => $in['env'] ?? 'production',
            'app_url' => rtrim($in['app_url'], '/'),
            'allowed_origins' => [],
            'trust_proxy' => (int) ($in['trust_proxy'] ?? 0),
            'db' => ['host' => $in['db']['host'], 'port' => (int) $in['db']['port'], 'name' => $in['db']['name'], 'user' => $in['db']['user'], 'pass' => $in['db']['pass'], 'socket' => $in['db']['socket'] ?? ''],
            'secrets' => ['cookie' => Ids::hex(32), 'field_keys' => 'k1:' . Ids::hex(32)],
            'mail' => $in['mail'] ?? ['host' => '', 'port' => 587, 'user' => '', 'pass' => '', 'secure' => 'tls', 'from' => 'Anibros CRM <no-reply@localhost>'],
            'log_level' => ($in['env'] ?? 'production') === 'production' ? 'warn' : 'info',
        ];
        $file = APP_ROOT . '/config/config.php';
        $php = "<?php\n// Generated by the installer on " . gmdate('c') . ". Contains secrets: keep it out of version control and out of the web root if you can.\n// Losing secrets.field_keys makes stored integration tokens unreadable: back this file up with your database.\nreturn " . var_export($cfg, true) . ";\n";
        if (file_put_contents($file, $php, LOCK_EX) === false) throw new \RuntimeException('Cannot write config/config.php');
        @chmod($file, 0640);
        Config::load($file);
        return $file;
    }

    /** @return array{applied:string[],views:int} */
    public static function migrate(bool $verbose = false): array
    {
        $db = (array) Config::get('db');
        $pdo = Migrator::ensureDatabase($db);
        return Migrator::run($pdo, $verbose);
    }
}
